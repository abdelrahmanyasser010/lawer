foreach ($legalDocs as $key => $doc) {
    // 1. Upsert into legal_contents
    $existing = DB::table('legal_contents')->where('content_key', $key)->first();
    $nextVersion = 1;
    if ($existing) {
        $nextVersion = (int)($existing->current_published_version ?: 0) + 1;
        DB::table('legal_contents')->where('content_key', $key)->update([
            'title' => $doc['title'],
            'draft_body' => $doc['body'],
            'is_published' => true,
            'current_published_version' => $nextVersion,
            'published_at' => now(),
            'updated_at' => now(),
        ]);
    } else {
        DB::table('legal_contents')->insert([
            'content_key' => $key,
            'title' => $doc['title'],
            'draft_body' => $doc['body'],
            'is_published' => true,
            'current_published_version' => 1,
            'published_at' => now(),
            'created_at' => now(),
            'updated_at' => now(),
        ]);
    }

    // 2. Insert into legal_content_versions
    DB::table('legal_content_versions')->insert([
        'content_key' => $key,
        'version_number' => $nextVersion,
        'title' => $doc['title'],
        'body' => $doc['body'],
        'published_at' => now(),
        'created_at' => now(),
    ]);
}

